function info = run_macro(spec, info)
% Execute the generated CST BAS through COM. The BAS is still written as a
% manual fallback, but COM execution submits each CST VBA object block to
% AddToHistory so geometry appears in CST's model tree.
if ~isfield(spec, 'cst') || ~isfield(spec.cst, 'executable') || isempty(spec.cst.executable)
    warning('spec.cst.execute_cst=true but spec.cst.executable is empty. CST macro was generated only.');
    return;
end

exe = strtrim(char(spec.cst.executable));
macroPath = info.macro_path;
if ~exist(exe, 'file')
    warning('CST executable not found: %s', exe);
    return;
end
if ~exist(macroPath, 'file')
    warning('CST macro not found: %s', macroPath);
    return;
end

[macroFolder, macroName] = fileparts(macroPath);
runnerPath = fullfile(macroFolder, [macroName '_run_cst.bat']);
local_write_runner_bat(runnerPath, exe, macroPath);

info.executed = false;
info.runner_bat = runnerPath;

if ispc && (exist('actxserver', 'builtin') == 5 || exist('actxserver', 'file') == 2)
    currentStep = 'start CST COM server';
    try
        macroText = fileread(macroPath);
        cst = actxserver('CSTStudio.application');
        currentStep = 'create CST MWS project';
        mws = invoke(cst, 'NewMWS');
        currentStep = 'execute generated CST history blocks';
        [commandCount, lastCommand] = local_execute_macro_history(mws, macroText);
        currentStep = 'save CST project';
        local_save_project(mws, info.project_path);
        info.executed = true;
        info.launch_submitted = true;
        info.launch_status = 0;
        info.launch_method = 'COM AddToHistory blocks';
        info.command_count = commandCount;
        info.last_command = lastCommand;
        info.execution_note = 'CST model was generated by per-object AddToHistory blocks from the BAS macro.';
        return;
    catch ME
        info.com_failed_step = currentStep;
        info.com_error = getReport(ME, 'extended', 'hyperlinks', 'off');
        warning('%s', sprintf('CST COM automation failed at %s. BAS fallback remains available. Error: %s', ...
            currentStep, ME.message));
    end
end

% Fallback only opens CST non-blocking. The BAS file is the authoritative
% manual macro; do not open a generated MCS as a project.
cmd = sprintf('cmd /c start "" "%s" -m "%s"', exe, macroPath);
[status, out] = system(cmd);
info.launch_submitted = (status == 0);
info.launch_status = status;
info.launch_output = out;
info.launch_command = cmd;
info.launch_method = 'nonblocking command-line fallback';
info.execution_note = ['CST command-line macro execution is version-dependent. ', ...
    'If CST opens the start page, run the generated BAS from Macro Editor.'];
end

function [commandCount, lastCommand] = local_execute_macro_history(mws, macroText)
lines = regexp(macroText, '\r\n|\n|\r', 'split');
commandCount = 0;
lastCommand = '';
idx = 1;
while idx <= numel(lines)
    line = strtrim(lines{idx});
    if local_skip_macro_line(line)
        idx = idx + 1;
        continue;
    end

    if startsWith(line, 'With ', 'IgnoreCase', true)
        [idx, blockName] = local_submit_with_block(mws, lines, idx);
        commandCount = commandCount + 1;
        lastCommand = blockName;
        continue;
    end

    local_submit_single_line(mws, line, idx);
    commandCount = commandCount + 1;
    lastCommand = sprintf('line %d: %s', idx, line);
    idx = idx + 1;
end
end

function [nextIdx, blockName] = local_submit_with_block(mws, lines, startIdx)
line = strtrim(lines{startIdx});
objectName = local_parse_with_object(line, startIdx);
blockName = sprintf('line %d: With %s', startIdx, objectName);
blockLines = lines(startIdx);
idx = startIdx + 1;
while idx <= numel(lines)
    blockLines{end+1} = lines{idx}; %#ok<AGROW>
    if strcmpi(strtrim(lines{idx}), 'End With')
        nextIdx = idx + 1;
        local_add_history(mws, blockName, strjoin(blockLines, newline), startIdx);
        return;
    end
    idx = idx + 1;
end
error('CST:UnclosedWithBlock', 'CST macro has an unclosed With block starting at line %d.', startIdx);
end

function local_submit_single_line(mws, line, lineNumber)
if startsWith(line, 'StoreParameter ', 'IgnoreCase', true)
    args = local_parse_args(line((length('StoreParameter ') + 1):end));
    if numel(args) ~= 2
        error('CST:StoreParameter', 'Invalid StoreParameter syntax at line %d: %s', lineNumber, line);
    end
    invoke(mws, 'StoreParameter', args{:});
    return;
end

if strcmpi(line, 'Rebuild')
    % Rebuild is illegal inside CST structure history macros. The geometry
    % is updated by AddToHistory blocks and SaveAs below, so old BAS files
    % that still contain Rebuild should just skip it here.
    return;
end

token = regexp(line, '^([A-Za-z]\w*)\.([A-Za-z]\w*)\s*(.*)$', 'tokens', 'once');
if isempty(token)
    error('CST:UnsupportedLine', 'Unsupported CST macro line %d: %s', lineNumber, line);
end
local_add_history(mws, sprintf('line %d: %s.%s', lineNumber, token{1}, token{2}), line, lineNumber);
end

function local_add_history(mws, name, text, lineNumber)
try
    invoke(mws, 'AddToHistory', name, text);
catch ME
    error('CST:AddToHistoryFailed', ...
        'CST AddToHistory failed at line %d (%s): %s', lineNumber, name, ME.message);
end
end

function tf = local_skip_macro_line(line)
tf = isempty(line) || ...
    startsWith(line, char(39)) || ...
    startsWith(line, 'Sub Main', 'IgnoreCase', true) || ...
    startsWith(line, 'On Error GoTo', 'IgnoreCase', true) || ...
    startsWith(line, 'Exit Sub', 'IgnoreCase', true) || ...
    startsWith(line, 'ErrHandler:', 'IgnoreCase', true) || ...
    startsWith(line, 'MsgBox ', 'IgnoreCase', true) || ...
    startsWith(line, 'End Sub', 'IgnoreCase', true) || ...
    startsWith(line, 'SaveAs ', 'IgnoreCase', true);
end

function objectName = local_parse_with_object(line, lineNumber)
token = regexp(line, '^With\s+([A-Za-z]\w*)\s*$', 'tokens', 'once');
if isempty(token)
    error('CST:WithBlock', 'Invalid With block syntax at line %d: %s', lineNumber, line);
end
objectName = token{1};
end

function args = local_parse_args(argText)
argText = strtrim(char(argText));
if isempty(argText)
    args = {};
    return;
end

quoted = regexp(argText, '"((?:[^"]|"")*)"', 'tokens');
if ~isempty(quoted)
    args = cell(1, numel(quoted));
    for k = 1:numel(quoted)
        args{k} = strrep(quoted{k}{1}, '""', '"');
    end
    return;
end

parts = regexp(argText, '\s*,\s*', 'split');
args = cellfun(@strtrim, parts, 'UniformOutput', false);
args = args(~cellfun(@isempty, args));
end

function local_write_runner_bat(runnerPath, exe, macroPath)
fid = fopen(runnerPath, 'w');
if fid < 0
    return;
end
cleanupObj = onCleanup(@() fclose(fid));
fprintf(fid, '@echo off\r\n');
fprintf(fid, 'REM CST command-line macro execution is version-dependent.\r\n');
fprintf(fid, 'REM If this opens the CST start page, run the BAS from Macro Editor.\r\n');
fprintf(fid, 'start "" "%s" -m "%s"\r\n', exe, macroPath);
clear cleanupObj;
end

function local_save_project(mws, projectPath)
try
    invoke(mws, 'SaveAs', projectPath, true);
catch
    try
        invoke(mws, 'saveas', projectPath, 'false');
    catch
        warning('CST model was built, but automatic SaveAs failed. Save the project manually.');
    end
end
end
